def summary(r: CheckResult) -> str:
    if r.name == "source_fidelity":
        return f"{r.n_compared:,} values compared, {r.n_mismatch:,} mismatches"
    if r.name.startswith("boundaries"):
        return f"{r.n_compared:,} districts, {r.n_mismatch:,} problems"
    if r.name == "raw_files" and r.notes:
        return r.notes[0]
    if r.name == "store" and r.stats:
        st = r.stats
        compared = (
            "stored values not compared with DBEDT"
            if st["values_compared"] is None
            else f"{st['values_compared']:,} stored values compared with DBEDT, {st['values_mismatched']:,} differ"
        )
        return (
            f"{st['pairs']:,} geography and indicator pairs checked, {compared}, "
            f"{st['api_only']:,} Census API only, {r.n_mismatch:,} problems"
        )
    if r.name == "blocks":
        agree = {d["chamber"]: d["share_agree"] for d in r.details if d.get("check") == "agreement"}
        shares = " and ".join(f"{c.title()} {v:.3%}" for c, v in agree.items())
        return (
            f"{r.n_compared:,} blocks, {r.n_mismatch:,} blocks where the two assignment methods differ "
            f"(people in agreeing blocks: {shares})"
        )
    if r.name == "apportionment":
        return f"{r.n_compared - r.n_mismatch:,} of {r.n_compared:,} indicator totals conserved"
    if r.name == "gazetteer":
        return f"{r.n_compared:,} places, {r.n_mismatch:,} problems"
    if r.name == "areas":
        return f"{r.n_compared:,} areas, {r.n_mismatch:,} problems"
    if r.name == "sites":
        return f"{r.n_compared:,} sites, {r.n_mismatch:,} problems"
    if r.name == "rules":
        return f"{r.n_compared:,} rule values compared with their sources, {r.n_mismatch:,} mismatches"
    if r.name == "irs_county":
        return f"{r.n_compared:,} counties compared, {r.n_mismatch:,} rows or inputs missing"
    if r.name == "irs_state":
        return f"{r.n_compared:,} state and district totals compared, {r.n_mismatch:,} mismatches"
    if r.name == "cms_county":
        return f"{r.n_compared:,} county residuals checked, {r.n_mismatch:,} problems"
    if r.name == "cms_districts":
        return f"{r.n_compared:,} chamber and indicator totals reconciled, {r.n_mismatch:,} problems"
    if r.name in ("hud_hcv", "chas"):
        return f"{r.n_compared:,} totals reconciled, {r.n_mismatch:,} mismatches"
    if r.name == "district_sums":
        return f"{r.n_compared:,} sums compared with the state, {r.n_mismatch:,} outside its margin of error"
    if r.name == "admin_counts":
        return f"{r.n_compared:,} program counts compared, {r.n_mismatch:,} not compared"
    if r.name == "places":
        return f"{r.n_compared:,} tract and district values checked against their ranges, {r.n_mismatch:,} problems"
    return f"{r.n_compared:,} compared, {r.n_mismatch:,} mismatches"


def _status(r: CheckResult) -> str:
    return "PASS" if r.passed else "FAIL"


def _title(name: str) -> str:
    return TITLES.get(name, name)


def _proves(name: str) -> str:
    return PROVES.get(name, PROVES.get(name.split("_")[0], ""))


def _num(v) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:,.2f}"
    return f"{v:,}" if isinstance(v, int) else str(v)


def _pct(v) -> str:
    return "n/a" if v is None or math.isnan(v) else f"{v:.2f}%"


def _apportionment_table(r: CheckResult) -> list[str]:
    rows = [d for d in r.details if d.get("kind") == "summary"]
    if not rows:
        return []
    out = [
        "",
        (
            "| Chamber | Indicator | Districts | Median abs. error | 90th percentile abs. error "
            "| Within direct MOE | Conserved |"
        ),
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for d in rows:
        within = d["share_within_moe"]
        out.append(
            f"| {d['chamber'].title()} | {LABELS.get(d['indicator'], d['indicator'])} | {d['n_districts']} "
            f"| {_pct(d['median_ape'])} | {_pct(d['p90_ape'])} "
            f"| {'n/a' if within is None else f'{within:.0%}'} | {'yes' if d['conserved'] else 'NO'} |"
        )
    out += [
        "",
        (
            "Absolute error is the absolute difference between the apportioned and the direct value, as a "
            "percent of the direct value. Within direct MOE means the apportioned value lies inside the 90% "
            "margin of error of the Census Bureau's direct estimate."
        ),
    ]
    return out


SUM_PARTS = {"house": "House sum", "senate": "Senate sum", "county": "County sum"}


def _sums_table(r: CheckResult) -> list[str]:
    by: dict[str, dict] = {}
    for d in r.details:
        by.setdefault(d["indicator"], {})[d["parts"]] = d
    parts = [p for p in SUM_PARTS if any(p in v for v in by.values())]
    out = [
        "",
        "| Indicator | State estimate | " + " | ".join(SUM_PARTS[p] for p in parts) + " | Within state MOE |",
        "| --- | ---: | " + " | ".join("---:" for _ in parts) + " | --- |",
    ]
    for ind, rows in by.items():
        first = next(iter(rows.values()))
        state = "n/a" if first["state"] is None else f"{first['state']:,.0f}"
        if first["state_moe"] is not None:
            state += f" ± {first['state_moe']:,.0f}"
        sums = ["n/a" if rows[p]["sum"] is None else f"{rows[p]['sum']:,.0f}" for p in parts]
        ok = all(rows[p]["passed"] for p in parts)
        out.append(f"| {ind} | {state} | " + " | ".join(sums) + f" | {'yes' if ok else 'NO'} |")
    return out


